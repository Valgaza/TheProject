"""Turn labelled examples into Laya training rows.

A row is what Laya's fine-tuning reads (the shape of the LocalLLaMA/
typed-decisions dataset): ``state``, ``questions`` and ``gold`` -- gold being
the target probability of each option. Questions are exactly the ones core
asks (nexus_core.decisions), so the model is trained on the wording it will
be served.

Sources, in order of trust:
  data/laya/synth_*.jsonl     generated by synth.py, labelled by category
  gate_decisions (Postgres)   real turns the LLM gate decided (--with-real);
                              its verdict is the teacher label

The hand-labelled sets in labels/ are never exported: they are the held-out
evaluation (evaluate.py).

    uv run python scripts/laya/export.py [--with-real]

Writes data/laya/train.jsonl and data/laya/val.jsonl (10% held out for
temperature calibration).
"""

from __future__ import annotations

import argparse
import asyncio
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "laya"
sys.path.insert(0, str(ROOT / "core"))
from nexus_core.decisions import GATE_QUESTIONS, WEB_INTENT_QUESTIONS  # noqa: E402

# Near-hard targets. 0.95 was tried first and squashed every confident "no"
# to ~0.05, leaving almost no gap between a decline and a weakly-scored fact;
# temperature calibration (finetune.py) handles confidence afterwards.
SURE = 0.99


def _two_way(options: list[str], yes: str, truth: bool) -> dict:
    no = next(o for o in options if o != yes)
    return {yes: SURE if truth else 1 - SURE, no: 1 - SURE if truth else SURE}


def gate_row(person_said: str, assistant_replied: str, worth: bool, tier: str | None) -> dict:
    state = {"person_said": person_said, "assistant_replied": assistant_replied[:400]}
    worth_q = GATE_QUESTIONS["worth_remembering"]
    questions = {"worth_remembering": worth_q}
    gold = {"worth_remembering": {"probabilities": _two_way(list(worth_q["criteria"]), "lasting_fact", worth)}}
    if worth and tier in ("user", "project"):
        questions["tier"] = GATE_QUESTIONS["tier"]
        gold["tier"] = {"probabilities": _two_way(["user", "project"], "user", tier == "user")}
    return {"state": json.dumps(state), "questions": json.dumps(questions), "gold": json.dumps(gold)}


def web_row(message: str, asks: bool) -> dict:
    q = WEB_INTENT_QUESTIONS["asks_for_web"]
    return {
        "state": json.dumps({"message": message}),
        "questions": json.dumps({"asks_for_web": q}),
        "gold": json.dumps({"asks_for_web": {"probabilities": _two_way(list(q["criteria"]), "web", asks)}}),
    }


async def _real_gate_rows() -> list[dict]:
    import asyncpg
    from dotenv import dotenv_values

    db = await asyncpg.connect(dotenv_values(ROOT / ".env")["DATABASE_URL"])
    rows = await db.fetch(
        "select user_message, assistant_message, persist, facts from gate_decisions "
        "where status = 'done' and decided_by = 'llm'"
    )
    await db.close()
    out = []
    for r in rows:
        facts = json.loads(r["facts"]) if isinstance(r["facts"], str) else (r["facts"] or [])
        tiers = {f.get("scope") for f in facts}
        tier = tiers.pop() if len(tiers) == 1 else None
        out.append(gate_row(r["user_message"], r["assistant_message"], bool(r["persist"]), tier))
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--with-real", action="store_true", help="add LLM-gated real turns")
    args = parser.parse_args()

    rows: list[dict] = []
    for line in (DATA / "synth_gate.jsonl").read_text().splitlines():
        r = json.loads(line)
        rows.append(gate_row(r["person_said"], r["assistant_replied"], r["worth_remembering"], r["tier"]))
    for line in (DATA / "synth_web.jsonl").read_text().splitlines():
        r = json.loads(line)
        rows.append(web_row(r["message"], r["asks_for_web"]))
    if args.with_real:
        rows.extend(asyncio.run(_real_gate_rows()))

    random.Random(20261004).shuffle(rows)
    n_val = max(1, len(rows) // 10)
    (DATA / "val.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows[:n_val]))
    (DATA / "train.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows[n_val:]))
    print(f"train {len(rows) - n_val}, val {n_val} rows in {DATA}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
